    private void btnAddPostActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddPostActionPerformed
        String secure = "public";
        if (cboPostSecurity.getSelectedIndex() == 1)
            secure = "private";
        
        String pType = "Text";
        if (cboPostType.getSelectedIndex() == 1)
            pType = "Image";
        
        int pid = Integer.valueOf(lblPostId.getText());
        int uid = Integer.valueOf((lblUser.getText()).substring(1, 5));
        
        if (pType.equals("Image")) {
            //int postID, int userID, String postSecurity, String date, String name, String description, String location
            
            Image obj = new Image(pid, uid, secure, lblDateTime.getText(), txtFilename.getText(), txtDescript.getText(), txtLocation.getText());
            AppData.postsAL.add(obj);
            
        }//if
        else {
            //int postID, int userID, String postSecurity, String date, String text
            //int uid = Integer.valueOf(lblUser.getText());
            
            Text obj = new Text(pid, uid, secure, lblDateTime.getText(), txtText.getText());
            AppData.postsAL.add(obj);
        }//if-else
        
        JOptionPane.showMessageDialog(null, pType + " successfully posted!", pType + "Post", JOptionPane.INFORMATION_MESSAGE);
        setupCtrls();
    }//GEN-LAST:event_btnAddPostActionPerformed

