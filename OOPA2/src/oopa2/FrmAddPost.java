    private void btnPathInfoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPathInfoActionPerformed
        JFileChooser fc1 = new JFileChooser();

        FileNameExtensionFilter imageFilter = new FileNameExtensionFilter("Image Files", "jpg", "jpeg", "png", "gif"); // Extensions: case-insensitive

        fc1.setFileFilter(imageFilter);

        int result = fc1.showOpenDialog(this);

        File selectedFile = fc1.getSelectedFile();
        if (selectedFile != null) {
            String name = selectedFile.getName();
            String fullpath = selectedFile.getPath();
            File path = fc1.getCurrentDirectory();
            String strPath = path.getAbsolutePath();
            txtFilename.setText(name);
            txtLocation.setText(fullpath);
        } //if
        else {
            JOptionPane.showMessageDialog(null, "No image file selected!", "Attach Image", JOptionPane.OK_OPTION);
        }//else
        
        Path sourcePath = Paths.get(txtLocation.getText());

        Path destination = Paths.get("src/pictures");

        Path destinationPath = destination.resolve(txtFilename.getText());

        try {
            // Validate that the source file exists and is readable
            if (!Files.exists(sourcePath)) {
                System.err.println("Error: Source file does not exist.");
                return;
            }
            if (!Files.isReadable(sourcePath)) {
                System.err.println("Error: Source file is not readable.");
                return;
            }
            // Copy file with REPLACE_EXISTING to overwrite if file already exists
            Files.copy(sourcePath, destinationPath, StandardCopyOption.REPLACE_EXISTING);

            System.out.println("File copied successfully from " 
                               + sourcePath + " to " + destinationPath);

        }//try
        catch (FileAlreadyExistsException e) {
            System.err.println("Error: Destination file already exists.");
        }//catch
        catch (NoSuchFileException e) {
            System.err.println("Error: Source file not found.");
        }//catch
        catch (IOException e) {
            System.err.println("I/O Error: " + e.getMessage());
        }//catch
    }//GEN-LAST:event_btnPathInfoActionPerformed

