    private void cboMonthActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cboMonthActionPerformed
        
        //NOTICE - Search "java jframe calendar date picker using comboboxes" and click "How can i make a calendar using JComboBox?"
        
        if (lblYear.getText().equals("Year") == false) {
            int year = Integer.valueOf(lblYear.getText());
            boolean leapyear = false;
            
            if (cboMonth.getSelectedIndex() == 4 || cboMonth.getSelectedIndex() == 6 || cboMonth.getSelectedIndex() == 9 || cboMonth.getSelectedIndex() == 11) {
                switch (cboDay.getItemCount()) {
                    case 31:
                        cboDay.removeItemAt(31); //Remove 31st day if selected month has less than 31 days
                        System.out.println("cheese2");
                        break;
                //else-if
                    case 28:
                        //re-add days to month if previous selected month was February
                        cboDay.addItem("29");
                        cboDay.addItem("30");
                        break;
                //re-add days to month if previous selected month was February - Leap Year
                    case 29:
                        cboDay.addItem("30");
                        break;
                    default:
                        break;
                }//switch
            }
            else if (cboMonth.getSelectedIndex() == 2) {
                if (cboDay.getItemCount() == 31)
                    cboDay.removeItemAt(31);
                
                cboDay.removeItemAt(30); //Remove 30th day if selected month is February

                //leap year validation
                if (year % 4 == 0) { // every year exactly divisible by 4 is a leap year
                    if (year % 100 == 0) // except for years exactly divisible by 100
                        if (year % 400 == 0) // unless they are exactly divisible by both 100 and 400, then they are leap years
                            leapyear = true;
                    leapyear = true;
                }//nested if

                //Remove February 29th for non-leap years
                if (leapyear == false)
                    cboDay.removeItemAt(29);
            }//if-else-if
            
            else if (cboDay.getItemCount() == 30 && (cboMonth.getSelectedIndex() != 4 || cboMonth.getSelectedIndex() != 6 || cboMonth.getSelectedIndex() != 9 || cboMonth.getSelectedIndex() != 11)) //re-add days to month if previous selected month has less than 31 days
                System.out.println("cheese3");
                cboDay.addItem("31");
        }//nested if
    }//GEN-LAST:event_cboMonthActionPerformed

