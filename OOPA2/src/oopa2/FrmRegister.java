    private void btnSignUpActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSignUpActionPerformed
        //perform validation
        
        if (txtForename.getText().equals("") || txtForename.getText().isBlank()) {
            JOptionPane.showMessageDialog(null, "Your forename cannot be blank!", "Missing Input", JOptionPane.OK_OPTION);
            txtForename.grabFocus();
            return;
        }//Forename presence check
        
        else if (txtSurname.getText().equals("") || txtSurname.getText().isBlank()) {
            JOptionPane.showMessageDialog(null, "Your surname cannot be blank!", "Missing Input", JOptionPane.OK_OPTION);
            txtSurname.grabFocus();
            return;
        }//Surname presence check
        
        else if (cboDay.getSelectedIndex() == 0 || cboMonth.getSelectedIndex() == 0 || lblYear.getText().equals("Year")) {
            JOptionPane.showMessageDialog(null, "Please enter a valid Date of Birth!", "Invalid Date of Birth", JOptionPane.OK_OPTION);
            if (cboDay.getSelectedIndex() == 0)
                cboDay.grabFocus();            
            else if (cboMonth.getSelectedIndex() == 0)
                cboMonth.grabFocus();            
            else
                jSlider1.grabFocus();            
            return;
        }//Date of Birth
        
        else if (txtEmail.getText().equals("") || txtEmail.getText().isBlank()) {
            JOptionPane.showMessageDialog(null, "Your e-mail cannot be blank!", "Missing Input", JOptionPane.OK_OPTION);
            txtEmail.grabFocus();
            return;
        }//E-mail presence check
        
        else if (txtEmail.getText().indexOf("@") == -1 && txtEmail.getText().indexOf(".") == -1) {
            JOptionPane.showMessageDialog(null, "You have no @ or .com domain! Please enter a valid e-mail!", "Invalid E-mail", JOptionPane.OK_OPTION);
            txtEmail.grabFocus();
            return;
        }//else-if checking presence of '@' and '.'
        
        else if ( txtEmail.getText().indexOf("@") == 0 || txtEmail.getText().indexOf(".") == 0 || txtEmail.getText().endsWith("@") || txtEmail.getText().endsWith(".") ) {
            JOptionPane.showMessageDialog(null, "You cannot have your @ or '.' at the start or end of your email! Please enter a valid e-mail!", "Invalid E-mail", JOptionPane.OK_OPTION);
            txtEmail.grabFocus();
            return;
        }//else-if checking '@' and '.' are not at the beginning or end of email input
        
        else if (txtEmail.getText().endsWith(".com") == false) {
            JOptionPane.showMessageDialog(null, "Your email should end with a '.com' domain! Please enter a valid e-mail!", "Invalid E-mail", JOptionPane.OK_OPTION);
            txtEmail.grabFocus();
            return;
        }//else-if checking email input ends with ".com"
        
        else if (pwdPassword.getText().equals("") || pwdPassword.getText().isBlank()) {
            JOptionPane.showMessageDialog(null, "Your password cannot be blank!", "Missing Input", JOptionPane.OK_OPTION);
            pwdPassword.grabFocus();
            return;
        }//end of if-else-if chain
                   
        //create user object
        //String userID, String forename, String surname, String dob, String email, String password, boolean locked, String lastLogin, String regDate, int friends
        String birthday = cboDay.getSelectedIndex() + "/" + cboMonth.getSelectedIndex() + "/" + lblYear.getText();
        int id = Integer.valueOf(lblUID.getText());
        User temp = new User(id, txtForename.getText(), txtSurname.getText(), birthday, txtEmail.getText(), pwdPassword.getText(), lblRegistered.getText());
        
        if(chkLocked.isSelected())
            temp.setLocked(true);
        else
            temp.setLocked(false);
        
        int ans = JOptionPane.showConfirmDialog(null, "Please check your details now before creating your account.\n\nDo you want to proceed?", "Confirm Account Creation", JOptionPane.YES_NO_OPTION);

        if (ans == 0) {
            AppData.usersAL.add(temp);
            JOptionPane.showMessageDialog(null, "You have successfully created an account!", "Account Created", JOptionPane.INFORMATION_MESSAGE);
            setupCtrls();
            this.dispose();
            AppData.menuScreen.setVisible(true);
        }
        else
            JOptionPane.showMessageDialog(null, "Account creation has been cancelled.", "Account Creation Aborted", JOptionPane.OK_OPTION);
    }//GEN-LAST:event_btnSignUpActionPerformed

