    private void lstPostIDsValueChanged(javax.swing.event.ListSelectionEvent evt) {//GEN-FIRST:event_lstPostIDsValueChanged
        String pidStr = listModel.get(lstPostIDs.getSelectedIndex()).toString().substring(0,5);
        int pid = Integer.valueOf(pidStr);
        
        Posts thePost = AppData.findPost(pid);
        lblPostInfo.setText(thePost.details());
        
        Posts pObj = (Posts) AppData.postsAL.get(lstPostIDs.getSelectedIndex());
        cboComments.removeAllItems();

        if (pObj.getComments().size() == 0)
            cboComments.addItem("No Comments Yet!");

        else {
            for(Object obj : pObj.getComments())
                cboComments.addItem(obj.toString());
        }//if-else

        try {
            Image imgObj = (Image) pObj;
            java.awt.Image pic;
            pic = Toolkit.getDefaultToolkit().getImage(getClass().getResource("/pictures/" + imgObj.getImageName()));
            //scale to label size
            pic = pic.getScaledInstance(lblPostInfo.getWidth(), lblPostInfo.getHeight(), 2);

            lblPostInfo.setIcon(new ImageIcon(pic));
        }//try
        catch(Exception ex) {
            System.out.println(ex.toString());
        }//catch
    }//GEN-LAST:event_lstPostIDsValueChanged

