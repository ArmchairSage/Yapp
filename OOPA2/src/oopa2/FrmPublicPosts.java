    private void btnAddCommentActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddCommentActionPerformed
        Posts pObj = (Posts) AppData.postsAL.get(lstPostIDs.getSelectedIndex());
        if (pObj.getComments().size() == 0)
            cboComments.removeAllItems();

        pObj.addComment("<html>" + AppData.loggedOn.basicInfo() + " " + AppData.genDateTime() + "<br><br>" + txtComment.getText() + "</html>");
        cboComments.addItem("<html>" + AppData.loggedOn.basicInfo() + " " + AppData.genDateTime() + "<br><br>" + txtComment.getText() + "</html>");
        txtComment.setText("");
    }//GEN-LAST:event_btnAddCommentActionPerformed

